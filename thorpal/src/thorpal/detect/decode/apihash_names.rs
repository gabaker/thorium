//! The curated name dictionary the API-hash matcher resolves hashes against.
//!
//! Shellcode and loaders resolve imports by hashing export names (FNV-1a,
//! ROR13, CRC32, multiply-rolling, ...) instead of carrying the strings, so
//! reversing a hash back to its name needs a dictionary of plausible names.
//! This one is **curated from model knowledge of well-known Windows exports,
//! DLL names, and process names** -- it was not generated from any system's
//! DLLs, so it is a best-effort list of the names malware actually resolves
//! rather than a complete export table. Callers supplement it at runtime with
//! `extra_names` when a loader hashes something uncommon.
//!
//! `Zw*` twins of the `Nt*` syscall stubs are deliberately not listed: the
//! matcher's variant logic derives them (see
//! [`super::apihash::NameVariants`]), so each pair costs one entry.

